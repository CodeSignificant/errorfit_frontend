  static TextStyle sSmallBlack(BuildContext context) {
    return TextStyle(
      fontSize: _sizeOnView(context: context, mobile: 12, tab: 12, web: 12),
      color: AppColors.black,
    );
  }

  static double _sizeOnView({
    required BuildContext context,
    required double mobile,
    required double tab,
    required double web,
  }) {
    final screenWidth = MediaQuery.of(context).size.width;
    if (screenWidth < minScreen) return mobile;
    if (screenWidth < tabScreen) return tab;
    return web;
  }
